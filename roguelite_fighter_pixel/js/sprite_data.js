// Helper: build a blank 48-row frame filled with '_'
function _blank() {
  const row = '_'.repeat(48);
  return Array.from({length: 48}, () => row);
}

// Helper: overlay a list of [row, col, char, len] patches onto a frame array
function _patch(frame, patches) {
  const rows = frame.map(r => r.split(''));
  for (const [r, c, ch, len] of patches) {
    if (r < 0 || r >= 48) continue;
    for (let i = 0; i < (len || 1); i++) {
      if (c + i >= 0 && c + i < 48) rows[r][c + i] = ch;
    }
  }
  return rows.map(r => r.join(''));
}

