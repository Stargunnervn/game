// =============================================================================
// Utility: generate a recolored sprite from hustler template
// Used for generic_enemy (tinted at render time) and boss variants
// =============================================================================
function _recolorFrame(frame, colorMap) {
  // colorMap: { oldChar: newChar, ... }
  return frame.map(row => {
    let out = '';
    for (let i = 0; i < row.length; i++) {
      const ch = row[i];
      out += colorMap[ch] !== undefined ? colorMap[ch] : ch;
    }
    return out;
  });
}

function _recolorSprites(src, colorMap) {
  const result = {};
  for (const state of Object.keys(src)) {
    result[state] = src[state].map(frame => _recolorFrame(frame, colorMap));
  }
  return result;
}

